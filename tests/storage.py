# 갤러리 저장소: 연결 안 됨(4181) / 비공개 저장소(4182)
import sys
from playwright.sync_api import sync_playwright
T='/home/claude/jaguk/tests'
def ok(c,m):
    print(('ok  ' if c else 'FAIL'),m)
    if not c: sys.exit(1)
def make(pg, base):
    pg.goto(base); pg.wait_for_timeout(2000)
    pg.get_by_role('button', name='폰트 만들기 시작').click(); pg.wait_for_timeout(300)
    pg.locator('.actions .btn.primary', has_text='로 하기').click(); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='다 썼어요, 찍으러 가기').click(); pg.wait_for_timeout(300)
    pg.locator('[data-testid=sheet-file]').set_input_files(f'{T}/photo2-q-pen.jpg')
    pg.get_by_text('번 시트를 읽었어요').first.wait_for(timeout=120000)
    pg.locator('.actions.sticky .btn.primary', has_text='다듬').click(); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='자모 확인하기').click(); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='폰트 만들기').click()
    pg.get_by_text('문장으로 써 보세요').wait_for(timeout=180000); pg.wait_for_timeout(600)
    pg.get_by_role('button', name='이름 짓고 내려받기').click(); pg.wait_for_timeout(1200)
with sync_playwright() as p:
    b=p.chromium.launch()
    # 1) 저장소 없음
    ctx=b.new_context(viewport={'width':1280,'height':900}, accept_downloads=True); pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    make(pg, 'http://localhost:4181/')
    ok(pg.locator('.gallery-off').count()==1 and not pg.locator('.share-opt input').is_checked() and pg.locator('.share-opt input').is_disabled(), 'no store: share off + explained before sealing')
    pg.fill('#fname','저장소 없음'); pg.locator('.seal-btn').focus(); pg.keyboard.press('Enter'); pg.wait_for_timeout(800)
    ok(pg.locator('.pub-error').count()==0, 'no store: no error after sealing')
    with pg.expect_download() as d: pg.get_by_role('button', name='.ttf 내려받기').click()
    ok(d.value.suggested_filename.endswith('.ttf'), 'no store: TTF still downloads')
    pg.screenshot(path=f'{T}/shots/storage-none-export.png')
    pg.goto('http://localhost:4181/#gallery'); pg.reload(); pg.wait_for_timeout(1500)
    ok(pg.locator('.setup-box').count()==1 and pg.locator('[role=alert]').count()==0, 'no store: gallery shows setup guide, not an error')
    pg.locator('.setup-box summary').click(); pg.wait_for_timeout(200)
    pg.screenshot(path=f'{T}/shots/storage-none-gallery.png')
    print('errors', errs); ok(not errs, 'no page errors'); ctx.close()
    # 2) 비공개 저장소
    ctx=b.new_context(viewport={'width':1280,'height':900}, accept_downloads=True); pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    make(pg, 'http://localhost:4182/')
    ok(pg.locator('.share-opt input').is_checked() and pg.locator('.gallery-off').count()==0, 'private store: share on')
    pg.fill('#fname','비공개 저장소 글씨'); pg.locator('.seal-btn').focus(); pg.keyboard.press('Enter')
    pg.get_by_text('갤러리에 올렸어요').wait_for(timeout=30000); ok(True, 'private store: published')
    pg.locator('.pub').get_by_role('button', name='갤러리 보기').click(); pg.wait_for_timeout(1500)
    src = pg.locator('.gcard-img img').first.get_attribute('src')
    ok(src.startswith('/api/fonts?file='), f'private store: preview via api ({src[:40]})')
    ok(pg.evaluate("[...document.querySelectorAll('.gcard-img img')].every(i => i.complete && i.naturalWidth > 0)"), 'private store: preview image loads')
    pg.locator('.gcard button').first.click(); pg.wait_for_selector('.gdetail textarea', timeout=15000)
    ok(True, 'private store: font loads in detail (via api)')
    with pg.expect_download() as d: pg.get_by_role('button', name='TTF 내려받기').click()
    ok(open(d.value.path(),'rb').read(4)==b'\x00\x01\x00\x00', 'private store: TTF download via api')
    print('errors', errs); ok(not errs, 'no page errors')
    print('STORAGE OK'); b.close()
